// hasOwnProperty : un nom importé comme « constructor » ou « __proto__ » ne doit pas
// renvoyer une propriété héritée d'Object (l'aperçu planterait).
export function linkIcon(name) {
  return Object.prototype.hasOwnProperty.call(LINK_ICONS, name) ? LINK_ICONS[name] : Link;
}
