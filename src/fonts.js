// Polices proposées dans l'Apparence (FONT_OPTIONS, lib/schema.js), livrées avec l'app en fichiers
// statiques par graisse : Chrome les intègre alors en TrueType dans les PDF imprimés. Une police
// variable (celle de Google Fonts, par exemple) y deviendrait du Type 3, que certains logiciels de
// recrutement lisent mal. Le navigateur ne télécharge que les fichiers de la police affichée (et,
// grâce aux unicode-range, seulement les jeux de caractères utilisés).
// Graisses : celles des modèles (400 à 800, ou les plus proches disponibles) et l'italique, utilisé
// par le profil du modèle Design (sans lui, le navigateur penche le romain, moins lisible).

